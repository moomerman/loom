// Package gogen generates Go code from checked templates.
//
// For each .hx file it writes one Go file declaring, per component:
//
//   - an assigns struct (TodoListAssigns) with one field per parameter,
//   - a render.Component value (TodoList),
//   - the static parts of the template (package-level render.Statics),
//   - a render function that computes the dynamic parts, given the
//     render.Scope (the mount prefix and assets) and the assigns.
//
// The output is gofmt'd and meant to be read: when a template misbehaves,
// the generated code is the next place to look.
package gogen

import (
	"bytes"
	"fmt"
	"go/format"
	"html"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"github.com/moomerman/loom/compiler/ast"
	"github.com/moomerman/loom/compiler/check"
	"github.com/moomerman/loom/compiler/goinfo"
	"github.com/moomerman/loom/compiler/style"
)

// RenderImport is the import path of the package generated code uses.
const RenderImport = "github.com/moomerman/loom/render"

// OutputName returns the generated file name for a template file:
// todo_list.hx -> todo_list_hx.go.
func OutputName(hxPath string) string {
	return strings.TrimSuffix(hxPath, filepath.Ext(hxPath)) + goinfo.GeneratedSuffix
}

// File generates the Go source for one template file.
func File(info *check.Info, f *ast.File) ([]byte, error) {
	pkg := info.Package
	if pkg == "" {
		pkg = filepath.Base(filepath.Dir(f.Source.Name))
	}
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by loom from %s. DO NOT EDIT.\n\n", filepath.Base(f.Source.Name))
	fmt.Fprintf(&out, "package %s\n\n", pkg)
	paths := imports(info, f)
	if len(paths) > 0 || len(f.Behaviors) > 0 {
		fmt.Fprintf(&out, "import (\n")
		if len(f.Behaviors) > 0 {
			fmt.Fprintf(&out, "\t_ \"embed\"\n\n")
		}
		fmt.Fprintf(&out, "\t%q\n", RenderImport)
		if len(paths) > 0 {
			fmt.Fprintf(&out, "\n")
		}
		for _, path := range paths {
			fmt.Fprintf(&out, "\t%q\n", path)
		}
		fmt.Fprintf(&out, ")\n")
	} else {
		fmt.Fprintf(&out, "import %q\n", RenderImport)
	}
	for _, b := range info.Behaviors {
		if b.File == f {
			behavior(&out, b)
		}
	}

	for _, comp := range info.Components {
		if comp.File != f {
			continue
		}
		g := &gen{info: info, comp: comp, prefix: lowerFirst(comp.Name), used: map[*check.Var]bool{}}
		g.component(&out)
	}

	src, err := format.Source(out.Bytes())
	if err != nil {
		// A bug in the generator; return the unformatted code to debug it.
		return out.Bytes(), fmt.Errorf("generated code for %s doesn't compile: %v", f.Source.Name, err)
	}
	return src, nil
}

// imports returns the import paths of the packages whose components the
// package calls or whose behaviors the file's components attach, among
// the file's imports, sorted. (An import a file doesn't use is an error.)
func imports(info *check.Info, f *ast.File) []string {
	used := map[string]bool{}
	for _, pkg := range info.Imported {
		used[pkg.Path] = true
	}
	for _, comp := range info.Components {
		if comp.File != f {
			continue
		}
		for _, b := range comp.Behaviors {
			if pkg := info.ImportedBehaviors[b]; pkg != nil {
				used[pkg.Path] = true
			}
		}
	}
	for _, comp := range info.Components {
		if comp.File == f && comp.Forms {
			used[check.FormImport] = true
		}
	}
	seen := map[string]bool{}
	var paths []string
	if used[check.FormImport] {
		seen[check.FormImport] = true
		paths = append(paths, check.FormImport)
	}
	for _, imp := range f.Imports {
		if used[imp.Path] && !seen[imp.Path] {
			seen[imp.Path] = true
			paths = append(paths, imp.Path)
		}
	}
	sort.Strings(paths)
	return paths
}

// behavior declares a behavior: its module, embedded from the file next to
// the template, and its render.Behavior.
func behavior(out *bytes.Buffer, b *check.Behavior) {
	js := lowerFirst(b.GoName) + "JS"
	fmt.Fprintf(out, "\n//go:embed %s.js\nvar %s string\n\n", b.Name, js)
	emits := ""
	if names := b.EmitNames(); len(names) > 0 {
		emits = fmt.Sprintf("Emits: []string{%s}, ", quoteAll(names))
	}
	fmt.Fprintf(out, "// %s is behavior %s, declared at %s:%s and attached with use:%s.\n", b.GoName, b.Name, filepath.Base(b.File.Source.Name), b.Decl.Pos, b.Name)
	fmt.Fprintf(out, "var %s = render.RegisterBehavior(&render.Behavior{ID: %q, Name: %q, %sJS: %s})\n", b.GoName, b.ID, b.Name, emits, js)
}

func quoteAll(names []string) string {
	q := make([]string, len(names))
	for i, n := range names {
		q[i] = strconv.Quote(n)
	}
	return strings.Join(q, ", ")
}

// gen generates the code for one component.
type gen struct {
	info    *check.Info
	comp    *check.Component
	prefix  string              // statics variable prefix, e.g. todoList
	statics []string            // declarations of statics variables
	temps   int                 // counter for temporary variables d0, d1, ...
	used    map[*check.Var]bool // :for variables referenced so far
	inHead  bool                // generating the children of <head>
}

func (g *gen) component(out *bytes.Buffer) {
	c := g.comp
	assigns := c.Name + "Assigns"

	// The render function is generated first, so the statics it declares
	// are known when they are written out above it.
	body := &body{}
	top := g.reserveStatics() // number the outermost statics 0
	p := g.parts(c.Decl.Body, body)
	body.line("return %s", g.renderedWith(top, p))

	fmt.Fprintf(out, "\n// %s holds the parameters of component %s.\n", assigns, c.Name)
	fmt.Fprintf(out, "type %s struct {\n", assigns)
	for _, prm := range c.Params {
		fmt.Fprintf(out, "\t%s %s\n", prm.GoName, prm.Type.GoString())
	}
	fmt.Fprintf(out, "}\n\n")
	for _, prm := range c.Params {
		if prm.Type.Kind != check.Enum {
			continue
		}
		e := prm.Type.Enum
		fmt.Fprintf(out, "// %s is the type of %s's %s parameter.\n", e.GoName, c.Name, prm.Name)
		fmt.Fprintf(out, "type %s string\n\n", e.GoName)
		fmt.Fprintf(out, "// The values of %s.\nconst (\n", e.GoName)
		for _, v := range e.Values {
			fmt.Fprintf(out, "\t%s %s = %q\n", e.GoConst(v), e.GoName, v)
		}
		fmt.Fprintf(out, ")\n\n")
	}
	fmt.Fprintf(out, "// %s is the component declared at %s:%s.\n", c.Name, filepath.Base(c.File.Source.Name), c.Decl.Pos)
	opts := ""
	if c.RootLayout {
		opts += "RootLayout: true, "
	}
	uses := g.uses()
	assets := ""
	if c.CSS != "" || len(uses) > 0 || len(c.Behaviors) > 0 {
		assets = g.prefix + "Assets"
		opts += "Assets: " + assets + ", "
	}
	var samples []string
	if !c.RootLayout {
		var reason string
		samples, reason = g.previews()
		if len(samples) > 0 {
			opts += "Previews: " + g.prefix + "Previews, "
		} else {
			opts += fmt.Sprintf("NoPreview: %q, ", reason)
		}
	}
	if evs := events(g.info, c); len(evs) > 0 {
		opts += "Events: []render.EventUse{" + strings.Join(evs, ", ") + "}, "
	}
	fmt.Fprintf(out, "var %s = render.Register(render.Component[%s]{Name: %q, Package: %q, %sRender: render%s})\n\n", c.Name, assigns, c.Name, g.info.Package, opts, c.Name)
	if len(samples) > 0 {
		fmt.Fprintf(out, "// %sPreviews are the samples the preview gallery shows.\n", g.prefix)
		fmt.Fprintf(out, "var %sPreviews = []render.Preview[%s]{\n%s,\n}\n\n", g.prefix, assigns, strings.Join(samples, ",\n"))
	}
	if assets != "" {
		fields := ""
		if c.CSS != "" {
			fields = "CSS: " + goString(c.CSS)
			if g.info.Tokens {
				fields += ", Tokens: " + TokensVar
			}
		}
		if len(c.Behaviors) > 0 {
			var bs []string
			for _, b := range c.Behaviors {
				bs = append(bs, g.behaviorName(b))
			}
			if fields != "" {
				fields += ", "
			}
			fields += "Behaviors: []*render.Behavior{" + strings.Join(bs, ", ") + "}"
		}
		fmt.Fprintf(out, "// %s holds the CSS and behaviors of %s and the components it calls.\n", assets, c.Name)
		fmt.Fprintf(out, "var %s = &render.Assets{%s}\n\n", assets, fields)
		if len(uses) > 0 {
			// Set in init, so components that call each other don't make
			// an initialization cycle.
			fmt.Fprintf(out, "func init() { %s.Uses = []render.Template{%s} }\n\n", assets, strings.Join(uses, ", "))
		}
	}
	fmt.Fprintf(out, "var (\n%s)\n\n", strings.Join(g.statics, ""))
	defaults := ""
	for _, prm := range c.Params {
		if prm.Type.Kind == check.Enum && prm.Default != nil {
			// An enum's zero value isn't one of its values, so Go code
			// that leaves the field empty gets the default too.
			defaults += fmt.Sprintf("if a.%s == \"\" {\na.%s = %s\n}\n", prm.GoName, prm.GoName, g.defaultValue(prm, ""))
		}
	}
	fmt.Fprintf(out, "func render%s(s *render.Scope, a %s) *render.Rendered {\n%s%s}\n", c.Name, assigns, defaults, body.String())
}

// uses returns the components the component calls, in the order they
// first appear.
func (g *gen) uses() []string {
	var names []string
	seen := map[string]bool{}
	var walk func(nodes []ast.Node)
	walk = func(nodes []ast.Node) {
		for _, n := range nodes {
			switch n := n.(type) {
			case *ast.Element:
				walk(n.Children)
			case *ast.ComponentCall:
				if callee := g.info.Calls[n]; callee != nil {
					name := g.qualify(callee, callee.Name)
					if !seen[name] {
						seen[name] = true
						names = append(names, name)
					}
				}
				for _, s := range n.Slots {
					walk(s.Children)
				}
				walk(n.Children)
			}
		}
	}
	walk(g.comp.Decl.Body)
	return names
}

// events returns the render.EventUse literals of the server events c
// sends by name: each `on:x="name"` in its markup, and in the components
// it calls, followed into other packages. Events a caller passes through
// an event parameter (`on:click={on_click}`) are the caller's, so they
// are left out; slot markup belongs to the component that writes it.
func events(info *check.Info, c *check.Component) []string {
	var out []string
	seen := map[*check.Component]bool{}
	var comp func(info *check.Info, c *check.Component)
	var walk func(info *check.Info, c *check.Component, nodes []ast.Node)
	use := func(c *check.Component, attrs []*ast.Attr) {
		var vals []string
		for _, a := range attrs {
			if name, ok := strings.CutPrefix(a.Name, "val-"); ok {
				vals = append(vals, strconv.Quote(name))
			}
		}
		for _, a := range attrs {
			on, ok := strings.CutPrefix(a.Name, "on:")
			if !ok || a.Kind != ast.AttrString {
				continue
			}
			lit := fmt.Sprintf("{Name: %q, On: %q", a.Value, on)
			if len(vals) > 0 {
				lit += ", Vals: []string{" + strings.Join(vals, ", ") + "}"
			}
			out = append(out, lit+fmt.Sprintf(", At: \"%s:%s\"}", filepath.Base(c.File.Source.Name), a.Pos))
		}
	}
	walk = func(info *check.Info, c *check.Component, nodes []ast.Node) {
		for _, n := range nodes {
			switch n := n.(type) {
			case *ast.Element:
				use(c, n.Attrs)
				walk(info, c, n.Children)
			case *ast.ComponentCall:
				use(c, n.Attrs)
				for _, s := range n.Slots {
					walk(info, c, s.Children)
				}
				walk(info, c, n.Children)
				if callee := info.Calls[n]; callee != nil {
					calleeInfo := info
					if imp := info.Imported[callee]; imp != nil {
						calleeInfo = imp.Info
					}
					comp(calleeInfo, callee)
				}
			}
		}
	}
	comp = func(info *check.Info, c *check.Component) {
		if seen[c] || c.Decl == nil || info == nil {
			return
		}
		seen[c] = true
		walk(info, c, c.Decl.Body)
	}
	comp(info, c)
	return out
}

// goString quotes s as a Go string, as a raw string when that is readable.
func goString(s string) string {
	if !strings.ContainsAny(s, "`\r") {
		return "`" + s + "`"
	}
	return strconv.Quote(s)
}

// TokensFile is the generated file holding a package's design tokens,
// and TokensVar the variable it declares.
const (
	TokensFile = "loom_tokens" + goinfo.GeneratedSuffix
	TokensVar  = "loomTokens"
)

// Tokens generates the Go file declaring a package's design tokens, or
// returns nil if the package's styles don't use any.
func Tokens(info *check.Info, tokens *style.Tokens) []byte {
	if !info.Tokens || tokens == nil {
		return nil
	}
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by loom from %s. DO NOT EDIT.\n\n", filepath.Base(tokens.File.Name))
	fmt.Fprintf(&out, "package %s\n\n", info.Package)
	fmt.Fprintf(&out, "import %q\n\n", RenderImport)
	fmt.Fprintf(&out, "// %s are the design tokens as CSS custom properties, linked by every\n", TokensVar)
	fmt.Fprintf(&out, "// page that renders a component of this package with styles.\n")
	css := tokens.CSS()
	if info.IsPackage {
		css = tokens.DefaultsCSS()
	}
	themes := ""
	if names := tokens.ThemeNames(); len(names) > 0 {
		var qs []string
		for _, n := range names {
			qs = append(qs, goString(n))
		}
		themes = ", Themes: []string{" + strings.Join(qs, ", ") + "}"
	}
	fmt.Fprintf(&out, "var %s = &render.Sheet{CSS: %s%s}\n", TokensVar, goString(css), themes)
	src, err := format.Source(out.Bytes())
	if err != nil {
		panic(err) // a bug in the generator
	}
	return src
}

// body collects the statements of a function body. Indentation is left to
// gofmt.
type body struct{ b strings.Builder }

func (b *body) line(format string, args ...any) {
	fmt.Fprintf(&b.b, format, args...)
	b.b.WriteByte('\n')
}

func (b *body) String() string { return b.b.String() }

// parts accumulates a template block's statics and the Go expressions for
// its dynamics.
type parts struct {
	statics []string
	cur     strings.Builder
	dyns    []string
}

func (p *parts) static(s string) { p.cur.WriteString(s) }

func (p *parts) dynamic(expr string) {
	p.statics = append(p.statics, p.cur.String())
	p.cur.Reset()
	p.dyns = append(p.dyns, expr)
}

func (p *parts) done() []string { return append(p.statics, p.cur.String()) }

// parts generates a block of nodes, emitting any statements it needs into b.
func (g *gen) parts(nodes []ast.Node, b *body) *parts {
	p := &parts{}
	g.nodes(nodes, p, b)
	return p
}

func (g *gen) nodes(nodes []ast.Node, p *parts, b *body) {
	for _, n := range nodes {
		g.node(n, p, b)
	}
}

func (g *gen) node(n ast.Node, p *parts, b *body) {
	switch n := n.(type) {
	case *ast.Text:
		p.static(n.Value)
	case *ast.Interp:
		p.dynamic(g.textExpr(n.X))
	case *ast.Element:
		if n.For != nil || n.If != nil {
			p.dynamic(g.directives(n.Directives, b, func(p *parts, b *body) { g.element(n, p, b, n.Key) }))
			return
		}
		g.element(n, p, b, nil)
	case *ast.ComponentCall:
		switch n.Name {
		case check.LoomScripts:
			p.dynamic("render.LoomScripts(s)")
			return
		case check.LoomStyles:
			p.dynamic("render.LoomStyles(s)")
			return
		case check.LiveMeta:
			p.dynamic("render.LiveMeta(s)")
			return
		case check.LiveTitle:
			p.dynamic(g.liveTitle(n))
			return
		}
		if n.For != nil || n.If != nil {
			p.dynamic(g.directives(n.Directives, b, func(p *parts, b *body) { p.dynamic(g.call(n, b)) }))
			return
		}
		p.dynamic(g.call(n, b))
	}
}

// element generates an HTML element. An element repeated by :for with a
// :key gets a data-loom-key attribute, so the client can match it to its
// DOM node across updates.
//
// In a component with a <style> block, every element also gets the
// component's scope class, which its scoped CSS selectors require, except
// <html>, <head> and what's in <head>, which nothing in a page styles.
func (g *gen) element(n *ast.Element, p *parts, b *body, key ast.Expr) {
	p.static("<" + n.Tag)
	if key != nil {
		p.dynamic(g.attrExpr(&ast.Attr{Name: "data-loom-key", Kind: ast.AttrExpr, X: key}))
	}
	if u := g.info.Uses[n]; u != nil {
		p.dynamic(g.use(n.Use, u))
	}
	scope := g.comp.Class
	head := strings.EqualFold(n.Tag, "head")
	if g.inHead || head || strings.EqualFold(n.Tag, "html") {
		scope = ""
	}
	for _, a := range n.Attrs {
		if a.Name == "class" && scope != "" {
			switch a.Kind {
			case ast.AttrBare:
				p.static(` class="` + scope + `"`)
			case ast.AttrString:
				p.static(` class="` + strings.ReplaceAll(a.Value, `"`, "&quot;") + " " + scope + `"`)
			case ast.AttrExpr:
				p.dynamic("render.Attr(\"class\", render.ScopedClass(" + g.textExpr(a.X) + ", \"" + scope + "\"))")
			}
			scope = ""
			continue
		}
		if a.Kind == ast.AttrExpr && strings.HasPrefix(a.Name, "on:") {
			p.dynamic(fmt.Sprintf("render.EventAttrs(%q, %s)", a.Name, g.expr(a.X)))
			continue
		}
		switch a.Kind {
		case ast.AttrBare:
			p.static(" " + a.Name)
		case ast.AttrString:
			p.static(" " + a.Name + `="` + strings.ReplaceAll(a.Value, `"`, "&quot;") + `"`)
		case ast.AttrExpr:
			p.dynamic(g.attrExpr(a))
		}
	}
	if scope != "" {
		p.static(` class="` + scope + `"`)
	}
	p.static(">")
	if n.Void {
		return
	}
	if head {
		g.inHead = true
		defer func() { g.inHead = false }()
	}
	g.nodes(n.Children, p, b)
	p.static("</" + n.Tag + ">")
}

// directives generates a tag with :for and/or :if as its own block,
// emitting the loop or condition into b and returning the variable that
// holds the result. inner generates the tag itself.
func (g *gen) directives(d ast.Directives, b *body, inner func(*parts, *body)) string {
	v := g.temp()
	statics := g.reserveStatics()
	if d.For == nil {
		b.line("var %s render.Dynamic = render.Empty", v)
		b.line("if %s {", g.expr(d.If))
		p := &parts{}
		inner(p, b)
		b.line("%s = %s", v, g.renderedWith(statics, p))
		b.line("}")
		return v
	}

	// Generate the parts that can refer to the loop variable first, so the
	// loop header can use "_" for a variable nothing reads.
	lv := g.info.LoopVars[d.For]
	key := "render.IntKey(i)"
	index := "_"
	if d.Key != nil {
		key = g.expr(d.Key)
		if g.info.Types[d.Key].Kind == check.Int {
			key = "render.IntKey(" + key + ")"
		}
	} else {
		index = "i"
	}
	cond := ""
	if d.If != nil {
		cond = g.expr(d.If)
	}
	ib := &body{}
	p := &parts{}
	inner(p, ib)
	loopVar := "_"
	if g.used[lv] {
		loopVar = g.loopVar(lv)
	}

	// The item statics are known only now, so the List is built after the loop.
	b.line("var %sItems []render.Item", v)
	b.line("for %s, %s := range %s {", index, loopVar, g.expr(d.For.List))
	if cond != "" {
		b.line("if !(%s) {", cond)
		b.line("continue")
		b.line("}")
	}
	b.b.WriteString(ib.String())
	b.line("%sItems = append(%sItems, render.Item{Key: %s, Dynamics: %s})", v, v, key, dynamics(p.dyns))
	b.line("}")
	g.setStatics(statics, p.done())
	b.line("%s := &render.List{Statics: %s, Items: %sItems}", v, statics, v)
	return v
}

// use generates the attributes of an element's use:.
func (g *gen) use(n *ast.Use, u *check.UseInfo) string {
	b := u.Behavior
	props := "nil"
	if len(b.Params) > 0 {
		given := map[string]ast.Expr{}
		for _, p := range n.Props {
			given[p.Name] = p.X
		}
		var kv []string
		for _, prm := range b.Params {
			var v string
			switch x := given[prm.Name]; {
			case x != nil:
				v = g.expr(x)
			case prm.Type.Kind == check.Enum:
				v = strconv.Quote(prm.Default.(*ast.Atom).Name)
			default:
				v = g.defaultValue(prm, "")
			}
			kv = append(kv, fmt.Sprintf("%q: %s", prm.Name, v))
		}
		props = "map[string]any{" + strings.Join(kv, ", ") + "}"
	}
	return fmt.Sprintf("render.Use(%s.ID, %s, %q)", g.behaviorName(b), props, u.Requires)
}

// behaviorName is the Go name of a behavior, qualified if it is imported.
func (g *gen) behaviorName(b *check.Behavior) string {
	if pkg := g.info.ImportedBehaviors[b]; pkg != nil {
		return pkg.Name + "." + b.GoName
	}
	return b.GoName
}

// qualify returns the Go name of something a component declares, as
// referred to from this package: Button, or components.Button.
func (g *gen) qualify(comp *check.Component, name string) string {
	if pkg := g.info.Imported[comp]; pkg != nil {
		return pkg.Name + "." + name
	}
	return name
}

// call generates a component call expression.
func (g *gen) call(n *ast.ComponentCall, b *body) string {
	callee := g.info.Calls[n]
	var fields []string
	given := map[string]bool{}
	var vals, hints []string
	for _, a := range n.Attrs {
		if name, ok := strings.CutPrefix(a.Name, "val-"); ok {
			vals = append(vals, fmt.Sprintf("{Name: %q, Value: %s}", name, g.attrText(a)))
		}
		if name, ok := strings.CutPrefix(a.Name, "optimistic:"); ok {
			hints = append(hints, fmt.Sprintf("{Name: %q, Value: %q}", name, html.EscapeString(a.Value)))
		}
	}
	for _, a := range n.Attrs {
		prm := callee.Param(a.Name)
		if prm == nil {
			continue // val-*
		}
		given[prm.Name] = true
		var val string
		switch {
		case prm.Type.Kind == check.Event && a.Kind == ast.AttrExpr:
			val = g.expr(a.X)
			if len(vals) > 0 {
				val += ".With(" + strings.Join(prefixAll("render.Val", vals), ", ") + ")"
			}
			if len(hints) > 0 {
				val += ".Hint(" + strings.Join(prefixAll("render.Val", hints), ", ") + ")"
			}
		case prm.Type.Kind == check.Event:
			val = fmt.Sprintf("render.Event{Name: %q", a.Value)
			if len(vals) > 0 {
				val += ", Vals: []render.Val{" + strings.Join(vals, ", ") + "}"
			}
			if len(hints) > 0 {
				val += ", Hints: []render.Val{" + strings.Join(hints, ", ") + "}"
			}
			val += "}"
		case prm.Type.Kind == check.Enum && a.Kind == ast.AttrString:
			val = g.qualify(callee, prm.Type.Enum.GoConst(a.Value))
		case prm.Type.Kind == check.Enum:
			if lit, ok := a.X.(*ast.StringLit); ok {
				val = g.qualify(callee, prm.Type.Enum.GoConst(lit.Value))
			} else {
				val = g.expr(a.X)
			}
		case a.Kind == ast.AttrBare:
			val = "true"
		case a.Kind == ast.AttrString:
			val = strconv.Quote(a.Value)
		default:
			val = g.expr(a.X)
		}
		fields = append(fields, prm.GoName+": "+val)
	}
	for _, prm := range callee.Params {
		if !given[prm.Name] && prm.Default != nil {
			fields = append(fields, prm.GoName+": "+g.defaultValue(prm, g.qualify(callee, "")))
		}
	}
	for _, s := range n.Slots {
		fields = append(fields, callee.Param(s.Name).GoName+": "+g.slot(s.Children))
	}
	if len(n.Children) > 0 {
		fields = append(fields, callee.Param("inner_block").GoName+": "+g.slot(n.Children))
	}
	if g.info.Imported[callee] != nil {
		return fmt.Sprintf("%s.Render(s, %s{%s})", g.qualify(callee, callee.Name), g.qualify(callee, callee.Name+"Assigns"), strings.Join(fields, ", "))
	}
	return fmt.Sprintf("render%s(s, %sAssigns{%s})", callee.Name, callee.Name, strings.Join(fields, ", "))
}

func prefixAll(prefix string, xs []string) []string {
	out := make([]string, len(xs))
	for i, x := range xs {
		out[i] = prefix + x
	}
	return out
}

// defaultValue is the Go value of a parameter's default; qual qualifies
// an enum constant declared in another package ("components.").
func (g *gen) defaultValue(prm *check.Param, qual string) string {
	switch d := prm.Default.(type) {
	case *ast.Atom:
		return qual + prm.Type.Enum.GoConst(d.Name)
	case *ast.Unary:
		return "-" + g.expr(d.X)
	}
	return g.expr(prm.Default)
}

// attrText is the escaped text of an attribute's value.
func (g *gen) attrText(a *ast.Attr) string {
	switch a.Kind {
	case ast.AttrString:
		return "render.Text(" + strconv.Quote(html.EscapeString(a.Value)) + ")"
	case ast.AttrBare:
		return `render.Text("true")`
	}
	return g.textExpr(a.X)
}

// liveTitle generates <.live_title>: a <title> that the client updates
// when the page's title changes.
func (g *gen) liveTitle(n *ast.ComponentCall) string {
	args := map[string]string{"default": `""`, "prefix": `""`, "suffix": `""`}
	for _, a := range n.Attrs {
		if a.Kind == ast.AttrString {
			args[a.Name] = strconv.Quote(a.Value)
		} else {
			args[a.Name] = g.expr(a.X)
		}
	}
	content := "nil"
	if len(n.Children) > 0 {
		content = g.slot(n.Children)
	}
	return fmt.Sprintf("render.LiveTitle(%s, %s, %s, %s)", args["prefix"], args["default"], args["suffix"], content)
}

// slot generates a slot as a closure over the caller's scope.
func (g *gen) slot(nodes []ast.Node) string {
	b := &body{}
	statics := g.reserveStatics()
	p := g.parts(nodes, b)
	b.line("return %s", g.renderedWith(statics, p))
	return "func() *render.Rendered {\n" + b.String() + "}"
}

// renderedWith returns a *render.Rendered literal for p, whose statics
// go in the reserved variable s.
func (g *gen) renderedWith(s string, p *parts) string {
	g.setStatics(s, p.done())
	if len(p.dyns) == 0 {
		return "&render.Rendered{Statics: " + s + "}"
	}
	return "&render.Rendered{Statics: " + s + ", Dynamics: " + dynamics(p.dyns) + "}"
}

func dynamics(dyns []string) string {
	if len(dyns) == 0 {
		return "nil"
	}
	if len(dyns) == 1 {
		return "[]render.Dynamic{" + dyns[0] + "}"
	}
	return "[]render.Dynamic{\n" + strings.Join(dyns, ",\n") + ",\n}"
}

// reserveStatics names a new statics variable before its parts are known,
// so that outer blocks get lower numbers than the blocks inside them.
func (g *gen) reserveStatics() string {
	g.statics = append(g.statics, "")
	return fmt.Sprintf("%s%d", g.prefix, len(g.statics)-1)
}

// setStatics declares the reserved statics variable name with parts.
func (g *gen) setStatics(name string, parts []string) {
	n, _ := strconv.Atoi(strings.TrimPrefix(name, g.prefix))
	var quoted []string
	for _, s := range parts {
		quoted = append(quoted, strconv.Quote(s))
	}
	g.statics[n] = fmt.Sprintf("%s = &render.Statics{ID: \"%s.%d\", Parts: []string{%s}}\n", name, g.comp.Name, n, strings.Join(quoted, ", "))
}

func (g *gen) temp() string {
	v := fmt.Sprintf("d%d", g.temps)
	g.temps++
	return v
}

// --- Expressions ---

// textExpr converts an expression to a render.Dynamic for text content.
func (g *gen) textExpr(e ast.Expr) string {
	x := g.expr(e)
	switch g.info.Types[e].Kind {
	case check.String:
		return "render.Escape(" + x + ")"
	case check.Enum:
		return "render.Escape(string(" + x + "))"
	case check.Int:
		return "render.Int(" + x + ")"
	case check.Float:
		return "render.Float(" + x + ")"
	case check.Bool:
		return "render.Bool(" + x + ")"
	}
	return x // HTML: already a render.Text or render.Dynamic
}

// attrExpr converts a dynamic attribute to a render.Text holding the whole
// attribute, e.g. ` class="done"`.
func (g *gen) attrExpr(a *ast.Attr) string {
	x := g.expr(a.X)
	name := strconv.Quote(a.Name)
	switch g.info.Types[a.X].Kind {
	case check.Bool:
		return "render.BoolAttr(" + name + ", " + x + ")"
	case check.Int:
		return "render.Attr(" + name + ", render.Int(" + x + "))"
	case check.Float:
		return "render.Attr(" + name + ", render.Float(" + x + "))"
	case check.Enum:
		return "render.Attr(" + name + ", render.Escape(string(" + x + ")))"
	}
	return "render.Attr(" + name + ", render.Escape(" + x + "))"
}

// precedence matches both the template language and Go.
var precedence = map[string]int{
	"||": 1, "&&": 2,
	"==": 3, "!=": 3, "<": 3, "<=": 3, ">": 3, ">=": 3,
	"+": 4, "-": 4, "*": 5, "/": 5, "%": 5,
}

// expr generates the Go expression for a template expression.
func (g *gen) expr(e ast.Expr) string {
	switch e := e.(type) {
	case *ast.Ident:
		v := g.info.Vars[e]
		if v.Param != nil {
			return "a." + v.Param.GoName
		}
		g.used[v] = true
		return g.loopVar(v)
	case *ast.StringLit:
		return strconv.Quote(e.Value)
	case *ast.IntLit:
		return strconv.FormatInt(e.Value, 10)
	case *ast.FloatLit:
		s := strconv.FormatFloat(e.Value, 'g', -1, 64)
		if !strings.ContainsAny(s, ".e") {
			s += ".0"
		}
		return s
	case *ast.BoolLit:
		return strconv.FormatBool(e.Value)
	case *ast.Field:
		if g.info.Types[e.X].Kind == check.Form {
			if g.info.Types[e].Kind == check.FormEntries {
				return g.operand(e.X) + ".Entries(" + strconv.Quote(e.Name) + ")"
			}
			return g.operand(e.X) + ".Field(" + strconv.Quote(e.Name) + ")"
		}
		return g.operand(e.X) + "." + g.info.Fields[e].GoName
	case *ast.Index:
		if g.info.Types[e.X].Kind == check.FormEntries {
			return g.operand(e.X) + ".Key(" + g.str(e.Index) + ")"
		}
		return g.operand(e.X) + "[" + g.expr(e.Index) + "]"
	case *ast.Call:
		var args []string
		for _, a := range e.Args {
			args = append(args, g.expr(a))
		}
		h := g.info.Helpers[e]
		switch {
		case h.Name == "raw" && h.Builtin:
			return "render.Text(" + args[0] + ")"
		case h.Name == "render_slot" && h.Builtin:
			return "render.RenderSlot(" + args[0] + ")"
		case h.Name == "path" && h.Builtin:
			return "render.Path(s, " + args[0] + ")"
		case h.Name == "asset" && h.Builtin:
			return "render.Asset(s, " + args[0] + ")"
		case h.Builtin:
			return h.Name + "(" + strings.Join(args, ", ") + ")"
		}
		return h.GoName + "(" + strings.Join(args, ", ") + ")"
	case *ast.Unary:
		return e.Op + g.operand(e.X)
	case *ast.Binary:
		prec := precedence[e.Op]
		return g.side(e.X, prec, false) + " " + e.Op + " " + g.side(e.Y, prec, true)
	case *ast.ClassList:
		var items []string
		for _, item := range e.Items {
			items = append(items, g.str(item))
		}
		return "render.Classes(" + strings.Join(items, ", ") + ")"
	case *ast.Cond:
		if e.Else == nil {
			return fmt.Sprintf("func() string {\nif %s {\nreturn %s\n}\nreturn \"\"\n}()", g.expr(e.Cond), g.str(e.Then))
		}
		t := g.info.Types[e].GoString()
		return fmt.Sprintf("func() %s {\nif %s {\nreturn %s\n}\nreturn %s\n}()", t, g.expr(e.Cond), g.expr(e.Then), g.expr(e.Else))
	}
	panic(fmt.Sprintf("gogen: unexpected expression %T", e))
}

// str generates a text expression as a Go string: enums are converted.
func (g *gen) str(e ast.Expr) string {
	if g.info.Types[e].Kind == check.Enum {
		if _, ok := e.(*ast.StringLit); ok {
			return g.expr(e)
		}
		return "string(" + g.expr(e) + ")"
	}
	return g.expr(e)
}

// side generates an operand of a binary operator, parenthesized only when
// precedence requires it.
func (g *gen) side(e ast.Expr, parent int, right bool) string {
	if b, ok := e.(*ast.Binary); ok {
		p := precedence[b.Op]
		if p < parent || (right && p == parent) {
			return "(" + g.expr(e) + ")"
		}
	}
	return g.expr(e)
}

// operand generates an expression used as the operand of a unary
// operator, selector or index, parenthesizing if needed.
func (g *gen) operand(e ast.Expr) string {
	switch e.(type) {
	case *ast.Binary, *ast.Cond:
		return "(" + g.expr(e) + ")"
	}
	return g.expr(e)
}

var tempName = regexp.MustCompile(`^d\d+(Items)?$`)

// loopVar returns the Go name for a :for variable: its template name,
// unless that would clash with Go or with names the generator uses.
func (g *gen) loopVar(v *check.Var) string {
	if reserved[v.Name] || tempName.MatchString(v.Name) {
		return v.Name + "_"
	}
	return v.Name
}

var reserved = map[string]bool{
	// names the generator uses
	"a": true, "i": true, "s": true, "render": true, "form": true,
	// Go keywords
	"break": true, "case": true, "chan": true, "const": true, "continue": true, "default": true,
	"defer": true, "else": true, "fallthrough": true, "for": true, "func": true, "go": true, "goto": true,
	"if": true, "import": true, "interface": true, "map": true, "package": true, "range": true,
	"return": true, "select": true, "struct": true, "switch": true, "type": true, "var": true,
	// predeclared identifiers generated code may use
	"len": true, "string": true, "int": true, "float64": true, "bool": true, "true": true, "false": true, "nil": true,
}

func lowerFirst(s string) string {
	if s == "" {
		return s
	}
	return strings.ToLower(s[:1]) + s[1:]
}
